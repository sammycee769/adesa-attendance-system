package com.adesa.attendance.attendance;

import java.time.LocalDate;
import java.util.UUID;

import com.adesa.attendance.attendance.dto.AttendanceActionRequest;
import com.adesa.attendance.attendance.dto.AttendanceHistoryResponse;
import com.adesa.attendance.attendance.dto.AttendanceRecordResponse;
import com.adesa.attendance.attendance.dto.AttendanceStatusResponse;
import com.adesa.attendance.security.AuthenticatedEmployee;

import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.http.HttpStatus;
import org.springframework.security.core.Authentication;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;

/**
 * The employee's own attendance.
 *
 * <p>The identity always comes from the authenticated session; the endpoints
 * accept no employee id. Only the employee who owns a record can read it.
 */
@RestController
@RequestMapping("/api/v1/attendance")
@Validated
@Tag(name = "Attendance", description = "Employee attendance sign-in, sign-out, status and history")
public class AttendanceController {

    private final AttendanceService attendanceService;

    public AttendanceController(AttendanceService attendanceService) {
        this.attendanceService = attendanceService;
    }

    @PostMapping("/sign-in")
    @ResponseStatus(HttpStatus.CREATED)
    @Operation(summary = "Sign in for the current workday",
            description = "Requires an active account, an approved registered device proven by a fresh "
                    + "single-use device proof, and a request from the approved office network. "
                    + "409 when the employee has already signed in today. The timestamp is generated by the server.")
    public AttendanceRecordResponse signIn(@Valid @RequestBody AttendanceActionRequest request,
                                           Authentication authentication,
                                           HttpServletRequest httpRequest) {
        UUID employeeId = AuthenticatedEmployee.from(authentication).employeeId();
        return attendanceService.signIn(httpRequest, employeeId, request.deviceProofId());
    }

    @PostMapping("/sign-out")
    @Operation(summary = "Sign out for the current workday",
            description = "Requires a valid sign-in for today, an approved registered device proven by a fresh "
                    + "single-use device proof, and a request from the approved office network. "
                    + "409 when there is no sign-in today or the workday was already signed out.")
    public AttendanceRecordResponse signOut(@Valid @RequestBody AttendanceActionRequest request,
                                            Authentication authentication,
                                            HttpServletRequest httpRequest) {
        UUID employeeId = AuthenticatedEmployee.from(authentication).employeeId();
        return attendanceService.signOut(httpRequest, employeeId, request.deviceProofId());
    }

    @GetMapping("/me/today")
    @Operation(summary = "My attendance state for the current workday",
            description = "Returns the state (NOT_SIGNED_IN, SIGNED_IN, SIGNED_OUT), the timestamps and which "
                    + "action the backend currently accepts.")
    public AttendanceStatusResponse today(Authentication authentication) {
        UUID employeeId = AuthenticatedEmployee.from(authentication).employeeId();
        return attendanceService.status(employeeId);
    }

    @GetMapping("/me/history")
    @Operation(summary = "My attendance history",
            description = "Own records only, newest workday first. Defaults to the last 30 workdays.")
    public AttendanceHistoryResponse history(
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate from,
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate to,
            @RequestParam(defaultValue = "0") @Min(0) int page,
            @RequestParam(defaultValue = "20") @Min(1) @Max(100) int size,
            Authentication authentication) {
        UUID employeeId = AuthenticatedEmployee.from(authentication).employeeId();
        return attendanceService.history(employeeId, from, to, page, size);
    }
}
