package com.adesa.attendance.admin;

import static com.adesa.attendance.admin.AttendanceReportLayout.*;

import com.adesa.attendance.attendance.DailyAttendanceReport;
import com.adesa.attendance.attendance.DailyAttendanceReport.Day;
import com.adesa.attendance.attendance.DailyAttendanceReport.Filter;
import com.adesa.attendance.attendance.DailyAttendanceReport.Status;
import com.lowagie.text.*;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.time.ZoneId;
import java.util.ArrayList;

final class AttendancePdfWriter {
    private static final Color NAVY = new Color(17,32,65);
    private static final Color GREEN = new Color(20,106,67);
    private static final Color RED = new Color(161,36,45);
    private static final Color AMBER = new Color(130,75,12);
    private static final Color GREY = new Color(75,87,105);
    private static final Color LIGHT = new Color(242,244,247);
    private static final Color RULE = new Color(217,222,230);

    private AttendancePdfWriter() {}

    static byte[] write(DailyAttendanceReport report, Filter filter) {
        var output = new ByteArrayOutputStream();
        var doc = new Document(PageSize.A4.rotate(),32,32,32,45);
        var zone = ZoneId.of(report.timezone());
        try {
            PdfWriter.getInstance(doc,output);
            doc.addTitle("ADESA HOLDINGS · Staff Attendance Report");
            var footer = new HeaderFooter(new Phrase(
                    "Confidential – For Internal Use Only  |  Generated by ADESA HQ  |  Page ",font(8,GREY,false)),true);
            footer.setBorder(Rectangle.TOP);
            footer.setBorderColor(RULE);
            footer.setAlignment(Element.ALIGN_CENTER);
            doc.setFooter(footer);
            doc.open();
            var header = new PdfPTable(new float[]{1,13});
            header.setWidthPercentage(100);
            try (var stream = AttendancePdfWriter.class.getResourceAsStream("/attendance/adesa-logo.png")) {
                if (stream == null) throw new IllegalStateException("ADESA report logo is missing");
                Image logo = Image.getInstance(stream.readAllBytes());
                logo.scaleToFit(46,52);
                var cell = new PdfPCell(logo,false);
                cell.setBorder(Rectangle.NO_BORDER);
                cell.setVerticalAlignment(Element.ALIGN_MIDDLE);
                header.addCell(cell);
            }
            var heading = new PdfPCell();
            heading.setBorder(Rectangle.NO_BORDER);
            heading.addElement(new Paragraph("ADESA HOLDINGS",font(11,NAVY,true)));
            heading.addElement(new Paragraph("STAFF ATTENDANCE REPORT",font(21,NAVY,true)));
            header.addCell(heading);
            doc.add(header);
            doc.add(new Paragraph("Reporting period  " + report.from() + " to " + report.to()
                    + "   |   Subsidiary  " + supplied(filter.subsidiary(),"All")
                    + "   |   Generated  " + TIME.format(report.generatedAt().atZone(zone)) + " (" + zone + ")",font(9,GREY,false)));
            var applied = new ArrayList<String>();
            addFilter(applied,"Employee",filter.search());
            if (filter.employeeId() != null) addFilter(applied,"Employee ID",filter.employeeId().toString());
            addFilter(applied,"Department",filter.department());
            if (filter.status() != null) addFilter(applied,"Status",filter.status().label());
            doc.add(new Paragraph("Filters  " + (applied.isEmpty() ? "All employees and statuses" : String.join("  |  ",applied)),font(9,GREY,false)));
            if (report.days().isEmpty()) doc.add(new Paragraph("No working days match the selected filters.",font(10,GREY,false)));
            for (Day day : report.days()) doc.add(dayTable(day,zone));
            doc.add(summary(report));
            var note = new Paragraph("Expected attendance uses verified rosters. Recorded clock-ins without a verified schedule "
                    + "are included in Present and excluded from the attendance percentage.",font(8,GREY,false));
            note.setSpacingBefore(7);
            doc.add(note);
            doc.close();
            return output.toByteArray();
        } catch (Exception ex) {
            throw new IllegalStateException("Failed to generate attendance PDF report",ex);
        }
    }

    private static PdfPTable dayTable(Day day, ZoneId zone) {
        var table = new PdfPTable(new float[]{3,9,15,10,10,10,10,7,12,15});
        table.setWidthPercentage(100);
        table.setSpacingBefore(13);
        table.setHeaderRows(3);
        table.setSplitRows(false);
        var band = new PdfPCell(new Phrase(DAY.format(day.date()),font(12,Color.WHITE,true)));
        band.setColspan(COLUMNS.size());
        band.setBackgroundColor(NAVY);
        band.setBorder(Rectangle.NO_BORDER);
        band.setPadding(8);
        table.addCell(band);
        var s = day.summary();
        var totals = new Phrase();
        append(totals,"Expected " + s.expected(),NAVY);
        append(totals,"Present " + s.present(),GREEN);
        append(totals,"Absent " + s.absent(),RED);
        append(totals,"Late " + s.late(),AMBER);
        append(totals,"Signed out " + s.signedOut(),GREY);
        append(totals,"Yet to sign out " + s.yetToSignOut(),GREY);
        append(totals,"Incomplete " + s.incomplete(),AMBER);
        append(totals,"Leave / excused " + s.approvedAbsences(),GREY);
        var summary = cell(totals,null);
        summary.setColspan(COLUMNS.size());
        summary.setPadding(7);
        table.addCell(summary);
        for (String column : COLUMNS) table.addCell(cell(new Phrase(column,font(8,NAVY,true)),LIGHT));
        int line = 0;
        for (var row : day.employees()) {
            var values = cells(row,++line,zone);
            for (int index = 0; index < values.size(); index++) {
                boolean status = index == 8;
                table.addCell(cell(new Phrase(values.get(index),font(8,status ? colour(row.status()) : NAVY,status)),null));
            }
        }
        return table;
    }

    private static PdfPTable summary(DailyAttendanceReport report) {
        var table = new PdfPTable(2);
        table.setWidthPercentage(100);
        table.setSpacingBefore(15);
        table.setKeepTogether(true);
        var title = new PdfPCell(new Phrase("Overall attendance summary",font(13,NAVY,true)));
        title.setBorder(Rectangle.NO_BORDER);
        title.setColspan(2);
        title.setPaddingBottom(7);
        table.addCell(title);
        for (var metric : metrics(report.summary())) {
            var card = new PdfPCell();
            card.setBackgroundColor(LIGHT);
            card.setPadding(7);
            card.setBorderColor(Color.WHITE);
            card.setBorderWidth(3);
            card.addElement(new Paragraph(metric.label(),font(9,GREY,false)));
            card.addElement(new Paragraph(metric.value(),font(14,NAVY,true)));
            table.addCell(card);
        }
        return table;
    }

    private static PdfPCell cell(Phrase contents, Color background) {
        var cell = new PdfPCell(contents);
        if (background != null) cell.setBackgroundColor(background);
        cell.setBorder(Rectangle.BOTTOM);
        cell.setBorderColor(RULE);
        cell.setPadding(5);
        return cell;
    }

    private static void append(Phrase phrase, String value, Color color) {
        if (!phrase.isEmpty()) phrase.add(new Chunk("    "));
        phrase.add(new Chunk(value,font(8,color,true)));
    }

    private static Color colour(Status status) {
        return switch (status) {
            case PRESENT, SIGNED_OUT -> GREEN;
            case ABSENT -> RED;
            case LATE, INCOMPLETE_ATTENDANCE -> AMBER;
            default -> GREY;
        };
    }

    private static Font font(int size, Color color, boolean bold) {
        return FontFactory.getFont(bold ? FontFactory.HELVETICA_BOLD : FontFactory.HELVETICA,size,color);
    }

    private static String supplied(String value, String fallback) { return value == null || value.isBlank() ? fallback : value; }
    private static void addFilter(java.util.List<String> filters, String label, String value) {
        if (value != null && !value.isBlank()) filters.add(label + " " + value.strip());
    }
}
